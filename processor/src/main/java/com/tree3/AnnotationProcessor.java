package com.tree3;

import javax.annotation.processing.AbstractProcessor;
import javax.annotation.processing.RoundEnvironment;
import javax.annotation.processing.SupportedAnnotationTypes;
import javax.annotation.processing.SupportedSourceVersion;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.Element;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.ExecutableElement;
import javax.lang.model.element.Modifier;
import javax.lang.model.element.TypeElement;
import javax.lang.model.type.TypeMirror;
import javax.lang.model.util.Types;
import javax.tools.Diagnostic;
import javax.tools.JavaFileObject;
import java.io.IOException;
import java.io.PrintWriter;
import java.util.LinkedHashSet;
import java.util.Set;

@SupportedAnnotationTypes("com.tree3.EventListener")
@SupportedSourceVersion(SourceVersion.RELEASE_25)
public class AnnotationProcessor extends AbstractProcessor {

    private static final String LISTENER_ADAPTER = "net.dv8tion.jda.api.hooks.ListenerAdapter";
    private static final String GENERATED_PACKAGE = "com.tree3.generated";
    private static final String GENERATED_CLASS = "GeneratedEventListeners";

    @Override
    public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment roundEnv) {
        Set<? extends Element> annotated = roundEnv.getElementsAnnotatedWith(EventListener.class);
        if (annotated.isEmpty()) {
            return false;
        }

        TypeElement listenerAdapter = processingEnv.getElementUtils().getTypeElement(LISTENER_ADAPTER);
        if (listenerAdapter == null) {
            processingEnv.getMessager().printMessage(Diagnostic.Kind.ERROR,
                    "Could not find " + LISTENER_ADAPTER + " on the classpath; is JDA a dependency?");
            return false;
        }
        TypeMirror listenerAdapterType = listenerAdapter.asType();
        Types types = processingEnv.getTypeUtils();

        Set<String> listeners = new LinkedHashSet<>();
        for (Element element : annotated) {
            if (element.getKind() != ElementKind.CLASS) {
                error(element, "@EventListener can only be applied to classes");
                continue;
            }
            TypeElement typeElement = (TypeElement) element;

            if (!types.isSubtype(typeElement.asType(), listenerAdapterType)) {
                error(element, "@EventListener class " + typeElement.getQualifiedName()
                        + " must extend " + LISTENER_ADAPTER);
                continue;
            }
            if (typeElement.getModifiers().contains(Modifier.ABSTRACT)) {
                error(element, "@EventListener class " + typeElement.getQualifiedName()
                        + " must not be abstract");
                continue;
            }
            if (typeElement.getNestingKind().isNested()
                    && !typeElement.getModifiers().contains(Modifier.STATIC)) {
                error(element, "@EventListener class " + typeElement.getQualifiedName()
                        + " must be a top-level or static nested class");
                continue;
            }
            if (!hasPublicNoArgConstructor(typeElement)) {
                error(element, "@EventListener class " + typeElement.getQualifiedName()
                        + " must have a public no-argument constructor");
                continue;
            }

            listeners.add(typeElement.getQualifiedName().toString());
        }

        generate(listeners);
        return true;
    }

    private boolean hasPublicNoArgConstructor(TypeElement typeElement) {
        for (Element enclosed : typeElement.getEnclosedElements()) {
            if (enclosed.getKind() != ElementKind.CONSTRUCTOR) {
                continue;
            }
            ExecutableElement constructor = (ExecutableElement) enclosed;
            if (constructor.getParameters().isEmpty()
                    && constructor.getModifiers().contains(Modifier.PUBLIC)) {
                return true;
            }
        }
        return false;
    }

    private void generate(Set<String> listeners) {
        String qualifiedName = GENERATED_PACKAGE + "." + GENERATED_CLASS;
        try {
            JavaFileObject file = processingEnv.getFiler().createSourceFile(qualifiedName);
            try (PrintWriter out = new PrintWriter(file.openWriter())) {
                out.println("package " + GENERATED_PACKAGE + ";");
                out.println();
                out.println("import java.util.List;");
                out.println("import net.dv8tion.jda.api.hooks.ListenerAdapter;");
                out.println();
                out.println("// Generated by com.tree3.AnnotationProcessor. Do not edit.");
                out.println("public final class " + GENERATED_CLASS + " {");
                out.println();
                out.print("    private static final List<ListenerAdapter> LISTENERS = List.of(");
                if (listeners.isEmpty()) {
                    out.println(");");
                } else {
                    out.println();
                    int i = 0;
                    for (String listener : listeners) {
                        String separator = (++i < listeners.size()) ? "," : "";
                        out.println("            new " + listener + "()" + separator);
                    }
                    out.println("    );");
                }
                out.println();
                out.println("    private " + GENERATED_CLASS + "() {");
                out.println("    }");
                out.println();
                out.println("    public static List<ListenerAdapter> getListeners() {");
                out.println("        return LISTENERS;");
                out.println("    }");
                out.println("}");
            }
        } catch (IOException e) {
            processingEnv.getMessager().printMessage(Diagnostic.Kind.ERROR,
                    "Failed to generate " + qualifiedName + ": " + e.getMessage());
        }
    }

    private void error(Element element, String message) {
        processingEnv.getMessager().printMessage(Diagnostic.Kind.ERROR, message, element);
    }
}
